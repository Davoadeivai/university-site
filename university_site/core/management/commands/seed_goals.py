class Command(BaseCommand):
    help = 'ثبت اهداف موسسه در پنج دستهٔ صفحهٔ اهداف'

    def add_arguments(self, parser):
        parser.add_argument('--replace', action='store_true',
                            help='شرح اهداف موجود هم بازنویسی شود')

    @transaction.atomic
    def handle(self, *args, **options):
        from core.models import InstitutionGoal

        replace = options['replace']
        created = updated = skipped = 0

        for index, (goal_type, title, description) in enumerate(GOALS, start=1):
            goal = InstitutionGoal.objects.filter(title=title).first()
            if goal is None:
                InstitutionGoal.objects.create(
                    title=title, description=description, goal_type=goal_type,
                    order=index, is_active=True,
                )
                created += 1
                self.stdout.write('  + %s' % title)
            elif replace:
                goal.description = description
                goal.goal_type = goal_type
                goal.order = index
                goal.is_active = True
                goal.save()
                updated += 1
                self.stdout.write('  ~ %s' % title)
            else:
                skipped += 1

        self.stdout.write(self.style.SUCCESS(
            '\n%d هدف جدید، %d به‌روز، %d دست‌نخورده.'
            % (created, updated, skipped)))
        self.stdout.write('ویرایش از پنل: /admin/core/institutiongoal/')
