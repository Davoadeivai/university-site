"""آیا فایلِ یک فیلد واقعاً روی سرور هست؟

چرا لازم شد
───────────
ردیف در دیتابیس نام فایل را دارد، ولی خودِ فایل ممکن است نباشد —
بعد از انتقال مدیا، یا وقتی کسی فایل را از روی دیسک برداشته. آن
وقت صفحه یک دکمهٔ دانلود نشان می‌دهد که کلیک رویش به ۴۰۴ می‌رسد.

روی سایت زنده همین بود: هر ۷۵ سند سرفصل و ده‌ها آیین‌نامه، نام
فایل داشتند و فایلشان نبود.

نکتهٔ کارایی
────────────
هر فراخوانی یک stat روی دیسک است. برای یک صفحه با چند ده ردیف
ناچیز است، ولی داخل حلقه‌ای با هزاران ردیف نباید صدا زده شود؛
آنجا بهتر است یک بار فهرست پوشه خوانده شود.
"""
from __future__ import annotations


def file_present(field_file) -> bool:
    """True فقط وقتی فیلد پر است و فایلش هم روی استوریج هست.

    هیچ استثنایی بیرون نمی‌دهد: صفحه‌ای که فقط می‌خواهد بداند دکمه
    را نشان بدهد یا نه، نباید به‌خاطر یک استوریج ناهمکار بترکد.
    """
    if not field_file:
        return False
    try:
        return field_file.storage.exists(field_file.name)
    except (OSError, ValueError, NotImplementedError):
        return False
